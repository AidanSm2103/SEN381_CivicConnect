using System.ComponentModel.DataAnnotations;
using Microsoft.AspNetCore.Mvc.ModelBinding.Validation;

namespace CivicConnect.Models
{
    /// <summary>
    /// Aggregate root of the Requests module. Owner of changes: RequestService (create) and
    /// RequestWorkflowService (status/assignment). Never deleted (FR-012).
    /// NOTE: this entity is NOT bound directly from forms any more - forms bind to CreateRequestViewModel.
    /// </summary>
    public class ServiceRequest
    {
        public int Id { get; set; }

        // FR-001: unique human-readable reference, e.g. "CC-2026-000123". Generated by IRequestRepository.NextReferenceNoAsync().
        public string ReferenceNo { get; set; } = string.Empty;

        // FR-002: category is mandatory and must come from the controlled Category list.
        [Required(ErrorMessage = "Please select a category.")]
        [Range(1, int.MaxValue, ErrorMessage = "Please select a category.")]
        [Display(Name = "Category")]
        public int CategoryId { get; set; }

        [ValidateNever]
        public Category? Category { get; set; }

        [Required]
        public string Description { get; set; } = string.Empty;

        // Persisted as string (see RequestStatus). Default keeps old behaviour.
        public RequestStatus Status { get; set; } = RequestStatus.Submitted;

        public DateTime SubmittedAt { get; set; } = DateTime.UtcNow;

        // Who submitted it (FR-001, FR-003, FR-004).
        public int RequesterId { get; set; }
        [ValidateNever]
        public User? Requester { get; set; }

        // Single assignee (FR-009). Null until assigned/accepted.
        public int? AssignedStaffId { get; set; }
        [ValidateNever]
        public User? AssignedStaff { get; set; }
        public DateTime? AssignedAt { get; set; }

        public DateTime? ResolvedAt { get; set; }
        public DateTime? ClosedAt { get; set; }

        // Optimistic concurrency token (FR-009 / D-004). Configured as IsRowVersion() in ServiceRequestConfiguration.
        public byte[] RowVersion { get; set; } = Array.Empty<byte>();

        public ICollection<StatusHistory> StatusHistory { get; set; } = new List<StatusHistory>();
        public ICollection<RequestComment> Comments { get; set; } = new List<RequestComment>();
    }
}
